"""Build the launcher, UltraTears Launcher.exe: the window that checks the dump and the PC, runs tools/setup.py --json
and starts the game (src/launcher/). It holds no code of the game, so a release ships it built; in Git only its source.

SDL3 (static, the one the game links) + Dear ImGui (third_party/imgui) + nanosvg and stb_image; the fonts, icons and
images of assets/launcher/ are compiled in, so the exe is one file. MSYS2 CLANG64 clang/ninja, as tools/build_game.py.
usage: python tools/build_launcher.py [--out <folder>] [--debug]   (default: dev-local/build/launcher)
"""
import argparse
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'tools'))
from toolchain import CLANG64, env as tool_env  # noqa: E402
import version  # noqa: E402

EXE = 'UltraTears Launcher.exe'
SOURCES = ['src/launcher/main.cpp', 'src/launcher/ui.cpp', 'src/launcher/setup_proc.cpp', 'src/launcher/platform.cpp',
           'src/launcher/text.cpp', 'src/launcher/json.cpp', 'src/launcher/media.cpp', 'src/launcher/update.cpp',
           'third_party/imgui/imgui.cpp', 'third_party/imgui/imgui_draw.cpp', 'third_party/imgui/imgui_tables.cpp',
           'third_party/imgui/imgui_widgets.cpp', 'third_party/imgui/backends/imgui_impl_sdl3.cpp',
           'third_party/imgui/backends/imgui_impl_sdlrenderer3.cpp']
ASSETS = ['fonts/Inter_18pt-Regular.ttf', 'fonts/Inter_18pt-Medium.ttf', 'fonts/MontserratAlternates-Bold.ttf',
          'fonts/MontserratAlternates-SemiBold.ttf', 'l_emblem.png', 'l_pattern.png', 'l_ic_check.svg', 'l_ic_error.svg',
          'l_ic_folder.svg', 'l_ic_warn.svg', 'l_ic_chevron.svg']
LIBS = ('-static -mwindows -lSDL3 -luser32 -lgdi32 -limm32 -lole32 -loleaut32 -lversion -luuid -ladvapi32 -lsetupapi '
        '-lshell32 -lwinmm -ldwmapi -lwinhttp -lbcrypt -liconv -lc++')


def esc(path):   # a path in a ninja build line
    return path.replace('$', '$$').replace(' ', '$ ').replace(':', '$:')


def write_if_changed(path, data):
    if not path.is_file() or path.read_bytes() != data:
        path.write_bytes(data)


def assets_c(build):
    """assets/launcher/* as byte arrays (build/assets.c) and their table: name, data, size."""
    out = ['/* Generated by tools/build_launcher.py from assets/launcher: do not edit. */', '#include <stddef.h>']
    table = []
    for i, name in enumerate(ASSETS):
        data = (ROOT / 'assets/launcher' / name).read_bytes()
        rows = [','.join(str(b) for b in data[k:k + 32]) for k in range(0, len(data), 32)]
        out.append(f'static const unsigned char a{i}[] = {{\n' + ',\n'.join(rows) + '};')
        table.append(f'  {{"{pathlib.PurePosixPath(name).name}", a{i}, {len(data)}}},')
    out.append('struct launcher_asset { const char *name; const unsigned char *data; size_t size; };')
    out.append('const struct launcher_asset launcher_assets[] = {\n' + '\n'.join(table) + '\n  {0, 0, 0}};')
    write_if_changed(build / 'assets.c', ('\n'.join(out) + '\n').encode())


def resources(build):
    v, commit = version.current()
    n = ','.join(str(x) for x in version.numbers(v))
    write_if_changed(build / 'version.h', f'#define ULTRS_VERSION "{v}"\n#define ULTRS_COMMIT "{commit}"\n'.encode())
    write_if_changed(build / 'launcher.rc', f'''1 ICON "assets/icon.ico"
1 VERSIONINFO
FILEVERSION {n}
PRODUCTVERSION {n}
BEGIN
  BLOCK "StringFileInfo"
  BEGIN
    BLOCK "040904B0"
    BEGIN
      VALUE "CompanyName", "UltraTears contributors"
      VALUE "FileDescription", "UltraTears Launcher"
      VALUE "FileVersion", "{v} ({commit})"
      VALUE "LegalCopyright", "GPL-3.0-or-later. Not affiliated with Nintendo."
      VALUE "OriginalFilename", "{EXE}"
      VALUE "ProductName", "UltraTears"
      VALUE "ProductVersion", "{v}"
    END
  END
  BLOCK "VarFileInfo"
  BEGIN
    VALUE "Translation", 0x409, 1200
  END
END
'''.encode())
    return v


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', type=pathlib.Path, default=ROOT / 'dev-local/build/launcher')
    ap.add_argument('--debug', action='store_true', help='-O0, a console for the log lines')
    a = ap.parse_args()
    build = a.out.resolve()
    (build / 'obj').mkdir(parents=True, exist_ok=True)
    assets_c(build)
    print(f'UltraTears Launcher {resources(build)}', flush=True)
    opt = '-O0' if a.debug else '-O2'
    b = build.as_posix()
    libs = LIBS.replace('-mwindows', '-mconsole') if a.debug else LIBS
    lines = [
        f'builddir = {b}',
        f'flags = {opt} -g -gcodeview -march=x86-64-v2 -Ithird_party/imgui -Ithird_party/imgui/backends -Ithird_party/nanosvg '
        f'-Ithird_party/stb -I{b} -DIMGUI_DISABLE_OBSOLETE_FUNCTIONS -DUNICODE -D_UNICODE',
        'rule cxx',
        '  command = clang++ -MD -MF $out.d $flags -std=c++17 -fno-exceptions -fno-rtti -Wall -Wno-unused-function -c $in -o $out',
        '  depfile = $out.d',
        '  deps = gcc',
        'rule cc',
        '  command = clang -MD -MF $out.d $flags -c $in -o $out',
        '  depfile = $out.d',
        '  deps = gcc',
        'rule rc',
        '  command = llvm-windres --target=pe-x86-64 -I . $in -o $out',
        'rule link',
        f'  command = clang++ -fuse-ld=lld -g -Wl,--pdb=$pdb -o $out $in {libs}',
        '',
    ]
    objs = []
    for src in SOURCES:
        obj = esc(f'{b}/obj/{src.rsplit(".", 1)[0].replace("/", "_")}.o')
        lines.append(f'build {obj}: cxx {src}')
        objs.append(obj)
    e = esc(b)
    lines.append(f'build {e}/obj/assets.o: cc {e}/assets.c')
    lines.append(f'build {e}/obj/launcher_res.o: rc {e}/launcher.rc | assets/icon.ico')
    objs += [f'{e}/obj/assets.o', f'{e}/obj/launcher_res.o']
    exe = esc(f'{b}/{EXE}')
    lines.append(f'build {exe}: link {" ".join(objs)}')
    lines.append(f'  pdb = {b}/UltraTears-Launcher.pdb')
    lines.append(f'default {exe}')
    write_if_changed(build / 'build.ninja', ('\n'.join(lines) + '\n').encode())
    rc = subprocess.run([str(CLANG64 / 'ninja.exe'), '-C', str(ROOT), '-f', str(build / 'build.ninja')], env=tool_env()).returncode
    if rc == 0:
        print(f'{build / EXE}')
    sys.exit(rc)


if __name__ == '__main__':
    main()
